FROM employees e JOIN orders o ON e.emp_id = o.emp_id 
JOIN order_details od ON o.ord_id = od.ord_id 
GROUP BY e.emp_id;

-- D. Average Order Value Handled Per Employee
SELECT 
    e.emp_name, 
    AVG(Order_Total) AS 'Avg_Order_Value_Per_Employee'
FROM 
    employees e
JOIN 
    orders o ON e.emp_id = o.emp_id
JOIN 
    (
        -- First: Calculate Total Price for EACH specific Order
        SELECT ord_id, SUM(total_price) AS Order_Total 
        FROM order_details 
        GROUP BY ord_id
    ) od_summary ON o.ord_id = od_summary.ord_id
GROUP BY 
    e.emp_id
ORDER BY 
    Avg_Order_Value_Per_Employee DESC;

