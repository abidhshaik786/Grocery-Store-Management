-- =======================================================
-- 1. CUSTOMER INSIGHTS
-- =======================================================

-- A. How many unique customers placed orders?
SELECT COUNT(DISTINCT cust_id) AS Unique_Customers FROM orders;

-- B. Which customers have placed the highest number of orders?
SELECT c.cust_name, COUNT(o.ord_id) AS Total_Orders 
FROM customers c JOIN orders o ON c.cust_id = o.cust_id 
GROUP BY c.cust_id ORDER BY Total_Orders DESC;

-- C. Total and Average purchase value per customer
SELECT c.cust_name, SUM(od.total_price) AS Total_Spent, AVG(od.total_price) AS Avg_Order_Value
FROM customers c JOIN orders o ON c.cust_id = o.cust_id 
JOIN order_details od ON o.ord_id = od.ord_id 
GROUP BY c.cust_id;

-- D. Top 5 Customers by total purchase amount
SELECT c.cust_name, SUM(od.total_price) AS Total_Revenue 
FROM customers c JOIN orders o ON c.cust_id = o.cust_id 
JOIN order_details od ON o.ord_id = od.ord_id 
GROUP BY c.cust_id ORDER BY Total_Revenue DESC LIMIT 5;

-- =======================================================
-- 2. PRODUCT PERFORMANCE
-- =======================================================

-- A. Products count in each category
SELECT cat.cat_name, COUNT(p.prod_id) AS Product_Count 
FROM categories cat JOIN products p ON cat.cat_id = p.cat_id 
GROUP BY cat.cat_id;

-- B. Average price of products by category
SELECT cat.cat_name, AVG(p.price) AS Avg_Price 
FROM categories cat JOIN products p ON cat.cat_id = p.cat_id 
GROUP BY cat.cat_id;

-- C. Highest sales volume (by quantity)
SELECT p.prod_name, SUM(od.quantity) AS Total_Qty_Sold 
FROM products p JOIN order_details od ON p.prod_id = od.prod_id 
GROUP BY p.prod_id ORDER BY Total_Qty_Sold DESC LIMIT 5;

-- D. Total revenue generated by each product
SELECT p.prod_name, SUM(od.total_price) AS Revenue 
FROM products p JOIN order_details od ON p.prod_id = od.prod_id 
GROUP BY p.prod_id ORDER BY Revenue DESC;

-- E. How do product sales vary by Category and Supplier?
SELECT 
    c.cat_name AS 'Category',
    s.sup_name AS 'Suppliers',
    SUM(od.total_price) AS 'Total_Revenue',
    SUM(od.quantity) AS 'Total_Units_Sold'
FROM 
    order_details od
JOIN 
    products p ON od.prod_id = p.prod_id
JOIN 
    categories c ON p.cat_id = c.cat_id
JOIN 
    supplier s ON p.sup_id = s.sup_id
GROUP BY 
    c.cat_name, s.sup_name
ORDER BY 
    Total_Revenue DESC;

-- =======================================================
-- 3. SALES AND ORDER TRENDS
-- =======================================================

-- A. Total orders placed
SELECT COUNT(*) AS Total_Orders FROM orders;

-- B. Average value per order
SELECT AVG(Order_Total) AS Avg_Order_Value 
FROM (SELECT ord_id, SUM(total_price) AS Order_Total FROM order_details GROUP BY ord_id) AS Table_Alies;

-- C. Most orders on which dates
SELECT order_date, COUNT(*) AS Orders_Count 
FROM orders GROUP BY order_date ORDER BY Orders_Count DESC LIMIT 5;

-- D. Monthly Trends: Orders & Revenue (Fixed)
SELECT 
    MONTHNAME(STR_TO_DATE(o.order_date, '%Y-%m-%d')) AS 'Month',
    COUNT(o.ord_id) AS 'Total_Orders_Volume',
    SUM(od.total_price) AS 'Total_Monthly_Revenue'
FROM 
    orders o
JOIN 
    order_details od ON o.ord_id = od.ord_id
GROUP BY 
    MONTHNAME(STR_TO_DATE(o.order_date, '%Y-%m-%d')), 
    MONTH(STR_TO_DATE(o.order_date, '%Y-%m-%d'))
ORDER BY 
    MONTH(STR_TO_DATE(o.order_date, '%Y-%m-%d'));
    
-- E. Weekday vs Weekend Order Patterns
SELECT 
    CASE 
        WHEN DAYOFWEEK(STR_TO_DATE(o.order_date, '%M %e, %Y')) IN (1, 7) THEN 'Weekend'
        ELSE 'Weekday'
    END AS Day_Pattern,
    COUNT(o.ord_id) AS Total_Orders,
    SUM(od.total_price) AS Total_Revenue
FROM 
    orders o
JOIN 
    order_details od ON o.ord_id = od.ord_id
GROUP BY 
    Day_Pattern;

